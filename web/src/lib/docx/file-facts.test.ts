import JSZip from "jszip";
import { describe, expect, it } from "vitest";
import { userPrompt } from "../ai/prompt";
import type { RuleContext } from "../rules/types";
import { fileFacts } from "./file-facts";
import { DocxPackage } from "./package";

const W = `xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"`;
const para = (text: string, rsid = "") => `<w:p${rsid ? ` w:rsidR="${rsid}"` : ""}><w:r><w:t>${text}</w:t></w:r></w:p>`;
const core = (creator: string, description = "") =>
  `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:creator>${creator}</dc:creator><dc:description>${description}</dc:description></cp:coreProperties>`;

async function facts(opts: { creator: string; description?: string; rsid?: string; header?: string }) {
  const zip = new JSZip();
  const body = Array.from({ length: 8 }, (_, i) => para(`Paragraph ${i}`, opts.rsid)).join("");
  zip.file("word/document.xml", `<w:document ${W}><w:body>${body}</w:body></w:document>`);
  zip.file("docProps/core.xml", core(opts.creator, opts.description));
  if (opts.header) zip.file("word/header1.xml", `<w:hdr ${W}>${para(opts.header)}</w:hdr>`);
  const pkg = await DocxPackage.load(await zip.generateAsync({ type: "uint8array" }));
  return fileFacts(pkg, (await pkg.xml("word/document.xml"))!);
}

describe("file facts for the AI-generated document rule", () => {
  it("recognise a file made by python-docx (what AI chat tools use) and never edited in Word", async () => {
    const f = await facts({ creator: "python-docx", description: "generated by python-docx", header: "MBA APPLICATION WORKING DRAFT" });
    expect(f).toEqual({ madeBy: "python-docx", neverEditedInWord: true, header: "MBA APPLICATION WORKING DRAFT", footer: "" });
  });

  it("see a file typed in Word as an ordinary file", async () => {
    expect(await facts({ creator: "A Student", rsid: "00A1B2C3" })).toEqual({ madeBy: undefined, neverEditedInWord: false, header: "", footer: "" });
  });

  it("are given to the AI with the document, and left out when there is nothing to say", async () => {
    const ctx: RuleContext = {
      fileName: "x.docx",
      docType: "Study Plan",
      fullText: "Hello",
      paras: [{ index: 0, text: "Hello", words: 1, sentences: 1, inTable: false, isList: false, isShort: true }],
    };
    const made = userPrompt({ ...ctx, file: await facts({ creator: "python-docx", header: "WORKING DRAFT" }) }, []);
    expect(made).toContain("<file_facts>");
    expect(made).toContain("created by python-docx");
    expect(made).toContain("never edited in Word");
    expect(made).toContain("- Page header: WORKING DRAFT");
    expect(userPrompt({ ...ctx, file: await facts({ creator: "A Student", rsid: "00A1B2C3" }) }, [])).not.toContain("<file_facts>");
  });
});
